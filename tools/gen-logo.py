#!/usr/bin/env python3
"""Turn an RGBA PNG (rsvg-convert output) into a C header for yupei-bootlog's
splash: the image composited over black as packed RGB, plus its size.

Usage: gen-logo.py logo.png logo.h
"""
import struct
import sys
import zlib


def read_png(path):
    data = open(path, 'rb').read()
    assert data[:8] == b'\x89PNG\r\n\x1a\n', 'not a PNG'
    pos, idat, w = 8, b'', 0
    while pos < len(data):
        n, kind = struct.unpack('>I4s', data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + n]
        if kind == b'IHDR':
            w, h, depth, ctype, _, _, interlace = struct.unpack('>IIBBBBB', body)
            assert depth == 8 and ctype == 6 and not interlace, 'need 8-bit RGBA, not interlaced'
        elif kind == b'IDAT':
            idat += body
        pos += 12 + n
    raw, bpp, stride = zlib.decompress(idat), 4, w * 4
    out, prev = bytearray(), bytearray(stride)
    for y in range(h):
        f = raw[y * (stride + 1)]
        line = bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0
            b = prev[x]
            c = prev[x - bpp] if x >= bpp else 0
            if f == 1:
                line[x] = (line[x] + a) & 255
            elif f == 2:
                line[x] = (line[x] + b) & 255
            elif f == 3:
                line[x] = (line[x] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                pred = a if pa <= pb and pa <= pc else b if pb <= pc else c
                line[x] = (line[x] + pred) & 255
        out += line
        prev = line
    return w, h, out


def main():
    w, h, px = read_png(sys.argv[1])
    rgb = bytearray()
    for i in range(0, len(px), 4):
        r, g, b, a = px[i:i + 4]
        rgb += bytes((r * a // 255, g * a // 255, b * a // 255))
    with open(sys.argv[2], 'w') as f:
        f.write(f'// Generated by gen-logo.py from {sys.argv[1].split("/")[-1]}\n')
        f.write(f'#define LOGO_W {w}\n#define LOGO_H {h}\n')
        f.write('static const unsigned char logo_rgb[] = {\n')
        for i in range(0, len(rgb), 24):
            f.write(','.join(str(v) for v in rgb[i:i + 24]) + ',\n')
        f.write('};\n')


if __name__ == '__main__':
    main()
